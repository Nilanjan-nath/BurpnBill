import { badRequest, notFound } from '../errors.js';

// Tables and their QR tokens. Scoped by restaurantId from the signed-in
// staff member, the same rule as everywhere else in this codebase.

// GET /tables — staff and owner; oldest first, so a new table lands at the
// bottom of the list rather than reshuffling ones already printed.
const TABLE_COLUMNS = 'id, label, seats, qr_token, is_active, pos_x, pos_y';

// Layout order, so the list beside the floor plan reads the way the room does
// — left to right, front to back. A table that has somehow lost its position
// sorts last rather than jumping to the front.
const LAYOUT_ORDER = 'pos_y nulls last, pos_x nulls last, created_at';

export async function listTables(db, restaurantId) {
  const { rows } = await db.query(
    `select ${TABLE_COLUMNS}
       from public.restaurant_tables
      where restaurant_id = $1 and deleted_at is null
      order by ${LAYOUT_ORDER}`,
    [restaurantId],
  );
  return rows;
}

// POST /tables — owner only. qr_token is generated by the database's own
// default (generate_opaque_token(), see the schema) — the API never invents
// one itself. A duplicate label is rejected by the table's own unique
// constraint (restaurant_id, label), surfacing as a 409 via errors.js's
// existing unique_violation mapping — no special-casing needed here.
export async function createTable(db, restaurantId, { label, seats, pos_x, pos_y }) {
  const { rows } = await db.query(
    `insert into public.restaurant_tables (restaurant_id, label, seats, pos_x, pos_y)
     select $1, $2, $3, coalesce($4, free.x), coalesce($5, free.y)
       from (
         -- The first genuinely free cell, row-major: not simply "however many
         -- tables there are", which would land on top of an existing one as
         -- soon as anything has been moved or retired.
         select gx.x, gy.y
           from generate_series(0, 19) as gy(y)
           cross join generate_series(0, 19) as gx(x)
          where not exists (
            select 1 from public.restaurant_tables t
             where t.restaurant_id = $1 and t.deleted_at is null
               and t.pos_x = gx.x and t.pos_y = gy.y
          )
          order by gy.y, gx.x
          limit 1
       ) as free
     returning ${TABLE_COLUMNS}`,
    [restaurantId, label, seats ?? null, pos_x ?? null, pos_y ?? null],
  );
  return rows[0];
}

// PATCH /tables/:tableId — owner only. Renaming and pausing, both deferred
// since step 5 and both now reachable from Settings → Seating Plan.
//
// Pausing is what `is_active` was always for: openMenu already refuses an
// inactive table with 403 `ordering_unavailable`, so a paused table's QR code
// stops taking orders the moment this is set — the code itself stays valid,
// which is the point. Nobody has to reprint anything to close a table for the
// evening.
//
// The qr_token is deliberately not touchable here. It is printed on something
// physical; changing it silently would turn every printed code on that table
// into a dead link.
export async function updateTable(db, restaurantId, tableId, input) {
  const { rows } = await db.query(
    `update public.restaurant_tables
        set label     = coalesce($3, label),
            seats     = case when $4::boolean then $5 else seats end,
            is_active = coalesce($6, is_active),
            pos_x     = coalesce($7, pos_x),
            pos_y     = coalesce($8, pos_y)
      where id = $1 and restaurant_id = $2 and deleted_at is null
      returning ${TABLE_COLUMNS}`,
    [
      tableId,
      restaurantId,
      input.label ?? null,
      'seats' in input,
      input.seats ?? null,
      input.is_active ?? null,
      input.pos_x ?? null,
      input.pos_y ?? null,
    ],
  );
  return rows[0] ?? null;
}

// DELETE /tables/:tableId — owner only, and a SOFT delete.
//
// It has to be: orders.table_id references this table ON DELETE CASCADE, so a
// real DELETE would take every order ever placed here — items, payments,
// timeline — out of the history the dashboard reports on. The row stays, stops
// appearing anywhere, and its QR code stops resolving.
//
// Refused while the table still owes money. Retiring a table mid-service would
// hide a bill somebody has not paid, and no screen would ever show it again.
export async function deleteTable(db, restaurantId, tableId) {
  return db.withTransaction(async (tx) => {
    const { rows: found } = await tx.query(
      `select id from public.restaurant_tables
        where id = $1 and restaurant_id = $2 and deleted_at is null
        for update`,
      [tableId, restaurantId],
    );
    if (!found[0]) return { ok: false, reason: 'not_found' };

    const { rows: owing } = await tx.query(
      `select count(*)::int as n, coalesce(sum(total_amount), 0)::numeric(12, 2) as total
         from public.orders
        where table_id = $1 and paid_at is null and status != 'cancelled'`,
      [tableId],
    );
    if (owing[0].n > 0) {
      return { ok: false, reason: 'unpaid_orders', unpaid_count: owing[0].n, unpaid_total: owing[0].total };
    }

    // is_active = false is load-bearing, not tidiness: guestSession.js,
    // dashboard.js's occupancy count and staffOrders.js's "can I put an order
    // here" check all gate on it, so clearing it retires the table everywhere
    // those look, without each of them having to learn about deleted_at.
    // Its cell is freed too, so the next table can be put where it stood.
    await tx.query(
      `update public.restaurant_tables
          set deleted_at = now(), is_active = false, pos_x = null, pos_y = null
        where id = $1 and restaurant_id = $2`,
      [tableId, restaurantId],
    );
    return { ok: true };
  });
}

// GET /tables/:tableId/bill (step 6) — owner only. The staff-side table bill:
// every unpaid, non-cancelled order on this table with its lines, so the
// counter can see exactly what's being settled before taking money. Scoped by
// table, unlike the customer's GET /bill, which is scoped to one guest session
// — at the counter you're settling the whole table, not one person's phone.
export async function getTableBill(db, restaurantId, tableId) {
  const { rows: tables } = await db.query(
    `select t.id, t.label, r.currency_code
       from public.restaurant_tables t
       join public.restaurants r on r.id = t.restaurant_id
      where t.id = $1 and t.restaurant_id = $2 and t.deleted_at is null`,
    [tableId, restaurantId],
  );
  if (!tables.length) throw notFound('Table not found');

  const [{ rows: orders }, { rows: items }] = await Promise.all([
    db.query(
      `select id, order_number, status, subtotal, tax_amount, total_amount, placed_at
         from public.orders
        where table_id = $1 and restaurant_id = $2 and paid_at is null and status != 'cancelled'
          -- Nobody owes for an order the counter hasn't accepted yet.
          and approved_at is not null
        order by placed_at, order_number`,
      [tableId, restaurantId],
    ),
    db.query(
      `select oi.order_id, oi.name_at_order as name, oi.price_at_order as price,
              oi.quantity, oi.special_instructions, oi.line_total
         from public.order_items oi
         join public.orders o on o.id = oi.order_id
        where o.table_id = $1 and o.restaurant_id = $2
          and o.paid_at is null and o.status != 'cancelled' and o.approved_at is not null
        order by oi.name_at_order, oi.id`,
      [tableId, restaurantId],
    ),
  ]);

  const sum = (field) => orders.reduce((acc, o) => acc + Number(o[field]), 0).toFixed(2);

  return {
    table: { id: tables[0].id, label: tables[0].label },
    currency_code: tables[0].currency_code,
    generated_at: new Date().toISOString(),
    orders: orders.map((order) => ({
      ...order,
      items: items
        .filter((item) => item.order_id === order.id)
        .map(({ order_id: _orderId, ...item }) => item),
    })),
    totals: { subtotal: sum('subtotal'), tax: sum('tax_amount'), total: sum('total_amount') },
  };
}

// POST /tables/:tableId/checkout (step 6) — owner only. Settles the table:
// records how the money was taken at the counter and marks its orders paid,
// which is what frees it on the floor map.
//
// This does NOT move money. Per ARCHITECTURE.md §2 the customer pays at the
// counter — cash, the cafe's own card machine, or a UPI QR — and this records
// which of those happened. That's why there's no gateway here and why
// `payments.provider_ref` stays null: it's reserved for the day a real
// gateway does move money.
//
// One payments row per order rather than one per table, because that's what
// the schema models (payments.order_id, and the payments_sync_order_paid_at
// trigger sets orders.paid_at off it — this never writes paid_at directly, so
// the two can't disagree). The caller's idempotency_key is suffixed per order
// so one checkout of a three-order table still satisfies the unique index;
// replaying the same key is then a no-op rather than a double-settle, which is
// what makes a double-tapped Confirm safe.
//
// Unlike the earlier stand-in this replaces, it settles orders in ANY live
// status, not just 'served'. Paying before the food lands is normal, and the
// old restriction existed only because checkout was then a blind one-tap
// button; the caller now confirms against an itemised bill (GET .../bill), so
// refusing to take money for a round still in the kitchen is the wrong
// default. An order's status lifecycle is independent of paid_at — the kitchen
// still cooks and serves it exactly as before.
export async function checkoutTable(db, restaurantId, tableId, { method, idempotencyKey }) {
  const { rows: tables } = await db.query(
    `select id from public.restaurant_tables where id = $1 and restaurant_id = $2 and deleted_at is null`,
    [tableId, restaurantId],
  );
  if (!tables.length) throw notFound('Table not found');

  // for update: two people settling one table at once serialise here rather
  // than both inserting, the same lock-first pattern as PATCH /orders/:id/status.
  const { rows: orders } = await db.query(
    `select id, total_amount from public.orders
      where table_id = $1 and restaurant_id = $2 and paid_at is null and status != 'cancelled'
        and approved_at is not null
      order by placed_at
      for update`,
    [tableId, restaurantId],
  );
  if (!orders.length) throw badRequest('Nothing to settle on this table');

  const { rows: paid } = await db.query(
    `insert into public.payments (restaurant_id, order_id, idempotency_key, method, status, amount)
     select $1, ord.id, $2 || ':' || ord.id::text, $3::public.payment_method, 'succeeded', ord.total_amount
       from unnest($4::uuid[]) as o(id)
       join public.orders ord on ord.id = o.id
     on conflict (idempotency_key) do nothing
     returning order_id, amount`,
    [restaurantId, idempotencyKey, method, orders.map((o) => o.id)],
  );

  return {
    settled_order_count: orders.length,
    amount: orders.reduce((acc, o) => acc + Number(o.total_amount), 0).toFixed(2),
    already_settled: paid.length === 0,
  };
}
